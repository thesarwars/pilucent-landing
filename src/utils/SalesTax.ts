type TaxInfo = {
  combined: number;
  code: string;
  county: string;
  mctd: boolean;
  breakdown: { state: number; mctd: number; local: number };
};

const STATE_RATE = 0.04;
const MCTD_RATE = 0.00375;

const COUNTIES: Record<string, { rate: number; code: string; nyc?: boolean; mctd?: boolean }> = {
  'NEW YORK': { rate: 0.08875, code: '8081', nyc: true },
  KINGS: { rate: 0.08875, code: '8081', nyc: true },
  BRONX: { rate: 0.08875, code: '8081', nyc: true },
  QUEENS: { rate: 0.08875, code: '8081', nyc: true },
  RICHMOND: { rate: 0.08875, code: '8081', nyc: true },
  // ... more counties from Pub 718
};

export function calculateTax(county: string): TaxInfo | null {
  const c = county.trim().toUpperCase();
  const info = COUNTIES[c];
  if (!info) return null;

  const state = STATE_RATE;
  const mctd = info.mctd || info.nyc ? MCTD_RATE : 0;
  const local = +(info.rate - state - mctd).toFixed(5);

  return {
    combined: info.rate,
    code: info.code,
    county: c,
    mctd: !!(info.mctd || info.nyc),
    breakdown: { state, mctd, local },
  };
}

